//! Offline UK-English definitions from Sam's compact Wiktionary extract.
//!
//! `data/dictionary/dictionary.dat` holds one
//! `lemma<TAB>pos<TAB>definition<TAB>example<TAB>synonyms<TAB>antonyms` line
//! per sense. `dictionary.idx` holds a fixed `(u32 offset, u32 length)` record
//! per line, sorted by lemma, so a lookup binary-searches the index and touches
//! only the pages it needs. `sounds.dat` holds the UK pronunciation and
//! hyphenated form, and `origin.dat` the etymology; both are separate so the
//! preview row never maps them.
//!
//! Every file is memory-mapped on first use and the mapping lives for the rest
//! of the process: the dictionary is lazy, not loaded into a heap table, and an
//! idle Sam pays nothing for it.
//!
//! The extract is generated by `scripts/build-dictionary.py` from Wiktionary
//! via Wiktextract. See `data/dictionary/LICENSE.wiktionary`.

use std::io;
use std::os::unix::io::AsRawFd;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

/// One sense of a word.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Sense {
    pub pos: &'static str,
    pub definition: &'static str,
    pub example: &'static str,
    pub synonyms: &'static str,
    pub antonyms: &'static str,
}

/// The small part the panel needs for its preview row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Preview {
    pub word: String,
    pub pos: &'static str,
    pub definition: &'static str,
}

/// Everything the detail card and the CLI show.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub word: String,
    pub pronunciation: &'static str,
    pub hyphenated: &'static str,
    pub origin: &'static str,
    pub senses: Vec<Sense>,
}

/// A fixed-record index over one data file.
struct Mapped {
    data: &'static [u8],
    index: &'static [u8],
}

impl Mapped {
    fn open(dir: &Path, name: &str) -> Result<Mapped, String> {
        let data_path = dir.join(format!("{name}.dat"));
        let index_path = dir.join(format!("{name}.idx"));
        let data = map(&data_path)?;
        let index = map(&index_path)?;
        if index.len() % 8 != 0 {
            return Err(format!(
                "{} is not a dictionary index (size {} is not a multiple of 8)",
                index_path.display(),
                index.len()
            ));
        }
        let mapped = Mapped { data, index };
        mapped.validate()?;
        Ok(mapped)
    }

    fn validate(&self) -> Result<(), String> {
        // Only the fixed-size index is read here. Checking every line would
        // touch the whole data file and defeat the lazy mapping.
        for i in 0..self.count() {
            let (offset, length) = self.record(i);
            if offset > self.data.len() || length > self.data.len() - offset {
                return Err(format!(
                    "dictionary index record {i} points outside the data file"
                ));
            }
        }
        Ok(())
    }

    fn count(&self) -> usize {
        self.index.len() / 8
    }

    fn record(&self, i: usize) -> (usize, usize) {
        let bytes = &self.index[i * 8..i * 8 + 8];
        let offset = u32::from_le_bytes(bytes[0..4].try_into().expect("4 bytes")) as usize;
        let length = u32::from_le_bytes(bytes[4..8].try_into().expect("4 bytes")) as usize;
        (offset, length)
    }

    fn line(&self, i: usize) -> &'static str {
        let (offset, length) = self.record(i);
        std::str::from_utf8(&self.data[offset..offset + length]).unwrap_or("")
    }

    fn key(&self, i: usize) -> &'static str {
        self.line(i).split('\t').next().unwrap_or("")
    }

    /// The first index whose lemma is `word` or later.
    fn lower_bound(&self, word: &str) -> usize {
        let mut lo = 0;
        let mut hi = self.count();
        while lo < hi {
            let mid = (lo + hi) / 2;
            if self.key(mid) < word {
                lo = mid + 1;
            } else {
                hi = mid;
            }
        }
        lo
    }

    /// The first line for `word`, if there is one.
    fn first(&self, word: &str) -> Option<&'static str> {
        let i = self.lower_bound(word);
        (i < self.count() && self.key(i) == word).then(|| self.line(i))
    }
}

struct Dictionary {
    senses: Mapped,
}

impl Dictionary {
    fn open_dir(dir: &Path) -> Result<Dictionary, String> {
        Ok(Dictionary {
            senses: Mapped::open(dir, "dictionary")?,
        })
    }

    fn senses(&self, word: &str) -> Vec<Sense> {
        let mut out = Vec::new();
        let count = self.senses.count();
        let mut i = self.senses.lower_bound(word);
        while i < count && self.senses.key(i) == word {
            let mut fields = self.senses.line(i).splitn(6, '\t');
            let _lemma = fields.next();
            let pos = fields.next().unwrap_or("noun");
            let definition = fields.next().unwrap_or("");
            let example = fields.next().unwrap_or("");
            let synonyms = fields.next().unwrap_or("");
            let antonyms = fields.next().unwrap_or("");
            if !definition.is_empty() {
                out.push(Sense {
                    pos,
                    definition,
                    example,
                    synonyms,
                    antonyms,
                });
            }
            i += 1;
        }
        out
    }
}

struct Sounds {
    lines: Mapped,
}

impl Sounds {
    fn get(&self, word: &str) -> Option<(&'static str, &'static str)> {
        let mut fields = self.lines.first(word)?.splitn(3, '\t');
        let _lemma = fields.next();
        let ipa = fields.next().unwrap_or("");
        let hyphenated = fields.next().unwrap_or("");
        Some((ipa, hyphenated))
    }
}

struct Origins {
    lines: Mapped,
}

impl Origins {
    fn get(&self, word: &str) -> Option<&'static str> {
        let mut fields = self.lines.first(word)?.splitn(2, '\t');
        let _lemma = fields.next();
        let origin = fields.next().unwrap_or("");
        (!origin.is_empty()).then_some(origin)
    }
}

fn map(path: &Path) -> Result<&'static [u8], String> {
    let file = std::fs::File::open(path)
        .map_err(|e| format!("cannot open {}: {e}", path.display()))?;
    let len = file
        .metadata()
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?
        .len() as usize;
    if len == 0 {
        return Err(format!("{} is empty", path.display()));
    }
    let pointer = unsafe {
        libc::mmap(
            std::ptr::null_mut(),
            len,
            libc::PROT_READ,
            libc::MAP_PRIVATE,
            file.as_raw_fd(),
            0,
        )
    };
    if pointer == libc::MAP_FAILED {
        return Err(format!(
            "cannot map {}: {}",
            path.display(),
            io::Error::last_os_error()
        ));
    }
    // Sam is one long-lived process. Keeping the mapping for its lifetime is
    // the point: the kernel can reclaim pages, and no heap table is built.
    Ok(unsafe { std::slice::from_raw_parts(pointer.cast::<u8>(), len) })
}

fn data_dirs() -> Vec<PathBuf> {
    let mut dirs = Vec::new();
    if let Some(dir) = std::env::var_os("SAM_DICTIONARY_DIR") {
        dirs.push(PathBuf::from(dir));
    }
    if let Some(dir) = std::env::var_os("XDG_DATA_HOME") {
        dirs.push(PathBuf::from(dir).join("sam").join("dictionary"));
    } else if let Some(home) = std::env::var_os("HOME") {
        dirs.push(
            PathBuf::from(home)
                .join(".local")
                .join("share")
                .join("sam")
                .join("dictionary"),
        );
    }
    let system = std::env::var_os("XDG_DATA_DIRS")
        .unwrap_or_else(|| "/usr/local/share:/usr/share".into());
    for dir in std::env::split_paths(&system) {
        dirs.push(dir.join("sam").join("dictionary"));
    }
    // Running from the checkout before `sam` is installed.
    dirs.push(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .join("data")
            .join("dictionary"),
    );
    dirs
}

fn data_dir() -> Result<&'static Path, String> {
    static DIR: OnceLock<Result<PathBuf, String>> = OnceLock::new();
    let found = DIR.get_or_init(|| {
        let mut tried = Vec::new();
        for dir in data_dirs() {
            if !tried.contains(&dir) {
                tried.push(dir.clone());
            }
            if dir.join("dictionary.dat").is_file() && dir.join("dictionary.idx").is_file() {
                return Ok(dir);
            }
        }
        Err(format!(
            "the dictionary data is not installed (looked in {}); install the sam dictionary package",
            tried
                .iter()
                .map(|p| p.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        ))
    });
    match found {
        Ok(dir) => Ok(dir),
        Err(error) => Err(error.clone()),
    }
}

fn dictionary() -> Result<&'static Dictionary, String> {
    static DICTIONARY: OnceLock<Result<Dictionary, String>> = OnceLock::new();
    match DICTIONARY.get_or_init(|| Dictionary::open_dir(data_dir()?)) {
        Ok(dictionary) => Ok(dictionary),
        Err(error) => Err(error.clone()),
    }
}

fn sounds() -> Option<&'static Sounds> {
    static SOUNDS: OnceLock<Option<Sounds>> = OnceLock::new();
    SOUNDS
        .get_or_init(|| {
            let dir = data_dir().ok()?;
            Sounds::open(dir).ok()
        })
        .as_ref()
}

fn origins() -> Option<&'static Origins> {
    static ORIGINS: OnceLock<Option<Origins>> = OnceLock::new();
    ORIGINS
        .get_or_init(|| {
            let dir = data_dir().ok()?;
            Origins::open(dir).ok()
        })
        .as_ref()
}

impl Sounds {
    fn open(dir: &Path) -> Result<Sounds, String> {
        Ok(Sounds {
            lines: Mapped::open(dir, "sounds")?,
        })
    }
}

impl Origins {
    fn open(dir: &Path) -> Result<Origins, String> {
        Ok(Origins {
            lines: Mapped::open(dir, "origin")?,
        })
    }
}

/// Inflected forms that the headword index does not contain. The rules are
/// deliberately conservative: a wrong hit is worse than no hit.
fn variants(word: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut push = |candidate: String| {
        if candidate.len() >= 2 && candidate != word && !out.contains(&candidate) {
            out.push(candidate);
        }
    };
    if let Some(base) = word.strip_suffix("'s") {
        push(base.to_owned());
    }
    if let Some(base) = word.strip_suffix("ies") {
        push(format!("{base}y"));
    }
    if let Some(base) = word.strip_suffix("ves") {
        push(format!("{base}f"));
        push(format!("{base}fe"));
    }
    if let Some(base) = word.strip_suffix("ied") {
        push(format!("{base}y"));
    }
    if let Some(base) = word.strip_suffix("es") {
        push(base.to_owned());
    }
    if let Some(base) = word.strip_suffix("s") {
        push(base.to_owned());
    }
    for suffix in ["ed", "ing", "er", "est", "ly"] {
        if let Some(base) = word.strip_suffix(suffix) {
            if !base.is_empty() {
                push(base.to_owned());
                let mut chars = base.chars();
                let last = chars.next_back();
                let before_last = chars.next_back();
                if last == before_last && last.is_some_and(|c| !"aeiou".contains(c)) {
                    push(chars.as_str().to_owned());
                }
                push(format!("{base}e"));
            }
        }
    }
    out
}

/// Resolve `word` to a headword and its senses, trying conservative inflections.
fn resolve_with(dictionary: &Dictionary, word: &str) -> Result<(String, Vec<Sense>), String> {
    let word = word.trim().to_lowercase();
    if word.is_empty() {
        return Err("give me a word to define".into());
    }
    let senses = dictionary.senses(&word);
    if !senses.is_empty() {
        return Ok((word, senses));
    }
    for variant in variants(&word) {
        let senses = dictionary.senses(&variant);
        if !senses.is_empty() {
            return Ok((variant, senses));
        }
    }
    Err(format!("no definition for {word:?}"))
}

fn resolve(word: &str) -> Result<(String, Vec<Sense>), String> {
    resolve_with(dictionary()?, word)
}

fn make_entry(
    headword: String,
    senses: Vec<Sense>,
    sounds: Option<&Sounds>,
    origins: Option<&Origins>,
) -> Entry {
    let (pronunciation, hyphenated) = sounds
        .and_then(|sounds| sounds.get(&headword))
        .unwrap_or(("", ""));
    let origin = origins
        .and_then(|origins| origins.get(&headword))
        .unwrap_or("");
    Entry {
        word: headword,
        pronunciation,
        hyphenated,
        origin,
        senses,
    }
}

/// The first sense, for the panel's preview row.
pub fn preview(word: &str) -> Option<Preview> {
    let (headword, senses) = resolve(word).ok()?;
    let first = senses.first()?;
    Some(Preview {
        word: headword,
        pos: first.pos,
        definition: first.definition,
    })
}

/// The full entry, including pronunciation and etymology.
pub fn entry(word: &str) -> Result<Entry, String> {
    let (headword, senses) = resolve(word)?;
    Ok(make_entry(headword, senses, sounds(), origins()))
}

fn preview_in(dir: &Path, word: &str) -> Option<Preview> {
    let dictionary = Dictionary::open_dir(dir).ok()?;
    let (headword, senses) = resolve_with(&dictionary, word).ok()?;
    let first = senses.first()?;
    Some(Preview {
        word: headword,
        pos: first.pos,
        definition: first.definition,
    })
}

fn entry_in(dir: &Path, word: &str) -> Result<Entry, String> {
    let dictionary = Dictionary::open_dir(dir)?;
    let (headword, senses) = resolve_with(&dictionary, word)?;
    let sounds = Sounds::open(dir).ok();
    let origins = Origins::open(dir).ok();
    Ok(make_entry(headword, senses, sounds.as_ref(), origins.as_ref()))
}

/// A plain-text rendering for the CLI and the execution result.
pub fn lookup(word: &str) -> Result<String, String> {
    let entry = entry(word)?;
    Ok(render_plain(&entry))
}

pub fn render_plain(entry: &Entry) -> String {
    let mut out = String::new();
    let title = if entry.hyphenated.is_empty() {
        entry.word.clone()
    } else {
        entry.hyphenated.to_owned()
    };
    out.push_str(&title);
    if !entry.pronunciation.is_empty() {
        out.push_str("  ");
        out.push_str(entry.pronunciation);
    }
    out.push('\n');

    let mut last_pos = "";
    let mut number = 0;
    for sense in &entry.senses {
        if sense.pos != last_pos {
            if !last_pos.is_empty() {
                out.push('\n');
            }
            out.push_str(&format!("{}:\n", sense.pos));
            last_pos = sense.pos;
            number = 0;
        }
        number += 1;
        out.push_str(&format!("  {number}. {}\n", sense.definition));
        if !sense.example.is_empty() {
            out.push_str(&format!("     e.g. {}\n", sense.example));
        }
        if !sense.synonyms.is_empty() {
            out.push_str(&format!("     synonyms: {}\n", sense.synonyms));
        }
        if !sense.antonyms.is_empty() {
            out.push_str(&format!("     antonyms: {}\n", sense.antonyms));
        }
    }
    if !entry.origin.is_empty() {
        out.push_str(&format!("\nOrigin\n  {}\n", entry.origin));
    }
    out.trim_end().to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .join("data")
            .join("dictionary")
    }

    fn dictionary() -> Dictionary {
        Dictionary::open_dir(&repo()).expect("the shipped dictionary opens")
    }

    #[test]
    fn finds_a_definition_and_its_pos() {
        let senses = dictionary().senses("serendipity");
        assert!(!senses.is_empty());
        assert_eq!(senses[0].pos, "noun");
        assert!(
            senses[0].definition.to_lowercase().contains("chance")
                || senses[0].definition.to_lowercase().contains("fortunate")
                || senses[0].definition.to_lowercase().contains("luck"),
            "{:?}",
            senses[0].definition
        );
    }

    #[test]
    fn keeps_several_senses_for_a_common_word() {
        let senses = dictionary().senses("run");
        assert!(senses.len() >= 2, "{senses:?}");
        assert!(senses.iter().any(|sense| sense.pos == "verb"));
    }

    #[test]
    fn carries_uk_sounds_and_origin() {
        let entry = entry_in(&repo(), "triumph").expect("entry");
        assert!(!entry.pronunciation.is_empty(), "{entry:?}");
        assert!(!entry.origin.is_empty(), "{entry:?}");
        assert!(entry.senses.iter().any(|sense| sense.pos == "noun"));
        assert!(entry.senses.iter().any(|sense| sense.pos == "verb"));
    }

    #[test]
    fn uk_spellings_borrow_the_other_variant() {
        let entry = entry_in(&repo(), "colour").expect("colour");
        assert!(
            entry.senses.iter().any(|sense| {
                let text = sense.definition.to_lowercase();
                text.contains("spectral") || text.contains("colour") || text.contains("hue")
            }),
            "{entry:?}"
        );
    }

    #[test]
    fn alternative_forms_resolve_to_their_headword() {
        let entry = entry_in(&repo(), "okay").expect("okay");
        assert!(
            entry
                .senses
                .iter()
                .any(|sense| sense.definition.to_lowercase().contains("approval")),
            "{entry:?}"
        );
    }

    #[test]
    fn preview_is_the_first_sense() {
        let preview = preview_in(&repo(), "serendipity").expect("preview");
        let entry = entry_in(&repo(), "serendipity").expect("entry");
        assert_eq!(preview.pos, entry.senses[0].pos);
        assert_eq!(preview.definition, entry.senses[0].definition);
    }

    #[test]
    fn inflected_forms_fall_back_to_the_headword() {
        for (word, headword) in [
            ("stories", "story"),
            ("boxes", "box"),
            ("wolves", "wolf"),
            ("cars", "car"),
        ] {
            let senses = dictionary().senses(word);
            assert!(senses.is_empty(), "{word} should not be a headword");
            let fallback = variants(word)
                .into_iter()
                .find_map(|variant| {
                    let senses = dictionary().senses(&variant);
                    (!senses.is_empty()).then_some(variant)
                })
                .unwrap_or_default();
            assert_eq!(fallback, headword, "{word}");
        }
    }

    #[test]
    fn unknown_words_are_empty_not_guessed() {
        assert!(dictionary().senses("zzzznotaword").is_empty());
        assert!(dictionary().senses("").is_empty());
    }

    #[test]
    fn output_names_the_word_and_the_sense() {
        let entry = entry_in(&repo(), "serendipity").expect("entry");
        let text = render_plain(&entry);
        assert!(text.starts_with("ser"), "{text}");
        assert!(text.contains("noun:"), "{text}");
    }
}
